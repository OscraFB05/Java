//operadores de asignacion
let miNumero =10;
console.log(miNumero); //10
miNumero =20;
console.log(miNumero); //20
//Operadore +=
miNumero +=5; //miNumero = miNumero + 5
console.log(miNumero);
//Operador -=
miNumero -=3; //miNumero = miNumero - 3
console.log(miNumero);
//Operador *=
miNumero *=2; //miNumero = miNumero * 2
console.log(miNumero);
//Operador /=
miNumero /=4; //miNumero = miNumero / 4
console.log(miNumero);
//Operador %=
miNumero %=3;
console.log(miNumero); //miNumero = miNumero % 3
//Operador **=
miNumero **=3; //miNumero = miNumero ** 3
console.log(miNumero);
